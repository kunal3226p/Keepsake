                FeatureHighlightRow(
                    icon = Icons.Rounded.Face,
                    title = "Family Face Recognition",
                    subtitle = "Select a family member's face once to find and tag them across your entire library."
                )
                FeatureHighlightRow(
                    icon = Icons.Rounded.GridView,
                    title = "Monthly Memory Collages",
                    subtitle = "Curate favorite moments each month into warm, shareable editorial collages."
                )
            }

